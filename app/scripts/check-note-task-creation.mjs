import assert from 'node:assert/strict';

export async function checkNoteTaskCreation(page, body, openNote, saveAndReload) {
    const first = '2026-09-28T02:03:04.000Z';
    const second = '2026-09-28T03:04:05.000Z';
    const third = '2026-09-28T04:05:06.000Z';
    const items = body.locator('li[data-type="taskItem"]');
    const html = () => body.evaluate(root => root.editor.getHTML());
    const dates = () => items.evaluateAll(nodes => nodes.map(node => [node.getAttribute('data-created-at'), node.getAttribute('data-completed-at')]));
    const task = (text, created = '') => `<li data-type="taskItem" data-checked="false"${created ? ` data-created-at="${created}"` : ''}><p>${text}</p></li>`;
    await page.clock.setFixedTime(new Date(first));
    await openNote('<ul data-type="taskList">' + task('旧待办') + task('无效日期', 'invalid') + '</ul>', '旧待办不补造创建时间');
    assert.deepEqual(await dates(), [[null, null], [null, null]]);
    assert.equal(await body.locator('time').count(), 0);
    await body.locator('p').filter({ hasText: '旧待办' }).click();
    await page.keyboard.insertText('补充');
    await body.getByRole('checkbox', { name: /：.*旧待办.*$/ }).check();
    assert.equal((await dates())[0][0], null, 'Editing or completing a legacy task does not invent creation time');
    await saveAndReload();
    assert.equal((await dates())[0][0], null);

    await openNote('<p>新待办甲</p>', '创建时间');
    await saveAndReload();
    await body.locator('p').click();
    await page.getByRole('button', { name: '待办列表', exact: true }).click();
    assert.deepEqual(await dates(), [[first, null]], 'Toolbar conversion stamps the new task');
    const stamp = items.first().locator('.note-task-created-at');
    assert.match(await stamp.innerText(), /^创建 \d{2}:03$/);
    assert.match(await stamp.getAttribute('title'), /^创建于 2026-09-28 \d{2}:03:04$/);
    const initial = await html();
    assert.doesNotMatch(initial, /<time|note-task-created-at/, 'Timestamp is metadata, not editable text');
    const count = await page.locator('.note-editor-count').innerText();
    await page.getByRole('button', { name: '撤销', exact: true }).click();
    assert.equal(await items.count(), 0);
    await page.clock.setFixedTime(new Date(second));
    await page.getByRole('button', { name: '重做', exact: true }).click();
    assert.equal(await html(), initial, 'Redo restores original creation time');
    assert.equal(await page.locator('.note-editor-count').innerText(), count);
    await body.press('Control+End');
    await page.keyboard.insertText('补充');
    assert.equal((await dates())[0][0], first, 'Typing does not refresh creation time');
    await body.press('Enter');
    assert.equal(await items.nth(1).getAttribute('data-created-at'), second);
    assert.equal(await items.nth(1).locator('.note-task-created-at').count(), 0, 'Empty tasks keep the typing placeholder');
    await page.keyboard.insertText('新待办乙');
    assert.deepEqual(await dates(), [[first, null], [second, null]], 'Enter creates an independent timestamp');
    await body.press('Tab');
    assert.equal(await items.first().locator('ul li').getAttribute('data-created-at'), second);
    await body.press('Shift+Tab');
    assert.deepEqual(await dates(), [[first, null], [second, null]], 'Indenting/outdenting retain creation time');
    await page.clock.setFixedTime(new Date(third));
    await body.getByRole('checkbox', { name: /：新待办甲补充$/ }).check();
    assert.deepEqual(await dates(), [[first, third], [second, null]], 'Creation and completion are separate');
    assert.equal(await items.first().locator('.note-task-created-at').isVisible(), true, 'Completing a task keeps creation time visible');
    assert.match(await items.first().locator('.note-task-completed-at').innerText(), /^完成 \d{2}:05$/);
    assert.match(await items.first().locator('.note-task-completed-at').getAttribute('title'), /^完成于 /);
    await page.getByRole('button', { name: '未完成在前', exact: true }).click();
    assert.deepEqual(await dates(), [[second, null], [first, third]], 'Sorting carries both timestamps');
    await body.getByRole('checkbox', { name: /：新待办甲补充$/ }).uncheck();
    assert.deepEqual(await dates(), [[second, null], [first, null]], 'Reopening keeps original creation time');
    const saved = await html();
    await saveAndReload();
    assert.equal(await html(), saved);
    await openNote(saved, 'HTML 复制导入保留创建时间');
    assert.deepEqual(await dates(), [[second, null], [first, null]]);
    await page.clock.setFixedTime(new Date('2026-09-29T04:05:06.000Z'));
    await page.evaluate(() => window.dispatchEvent(new Event('focus')));
    assert.match(await items.first().locator('.note-task-created-at').innerText(), /^创建 09-28 /);
    assert.equal(await html(), saved, 'Day rollover only updates presentation');

    await openNote('<p></p>', '键盘创建待办');
    await body.click();
    await page.keyboard.type('[ ] ');
    await page.keyboard.insertText('快捷输入待办');
    assert.equal(await items.count(), 1);
    assert.equal((await dates())[0][0], '2026-09-29T04:05:06.000Z');
    await saveAndReload();
    await page.setViewportSize({ width: 1100, height: 700 });
    assert.ok(await body.evaluate(root => root.scrollWidth <= root.clientWidth + 1));
    await page.screenshot({ path: 'ui-check.local/note-task-creation.png' });
    await page.setViewportSize({ width: 1280, height: 840 });
    await page.clock.setSystemTime(new Date());
    console.log('Passed: task creation via toolbar/Enter/input rule, independent completion, legacy compatibility, undo/redo, hierarchy, sorting, HTML round-trip, persistence and day rollover');
}
